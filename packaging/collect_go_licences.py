#!/usr/bin/env python3
"""Collect the licence files of every Go module compiled into the desktop binaries.

    python3 -I packaging/collect_go_licences.py --src WORK/src --target linux-amd64 --tags TAGS --out DIR

Runs `go list -deps` for ./cmd/tailscaled and ./cmd/tailscale with the target's GOOS/GOARCH and the build tags,
then copies each module's LICENSE*, COPYING*, NOTICE* and PATENTS* files from the module cache to
DIR/<module>@<version>/, plus the Go distribution's own LICENSE and PATENTS (the standard library is linked into
every binary) and the licence files of vendored sub-trees of the main module (for example tempfork/). Writes
DIR/INDEX.md. Fails if a linked module has no licence file, so a release can never ship without one.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import os

LICENCE_NAME = re.compile(r"(?i)^(licen[cs]e|copying|notice|patents|unlicense)([.-].*)?$")


def licence_files(d):
    return sorted(p for p in Path(d).iterdir() if p.is_file() and LICENCE_NAME.match(p.name))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True, type=Path)
    ap.add_argument("--target", required=True)
    ap.add_argument("--tags", required=True)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    goos, goarch = a.target.split("-", 1)
    env = dict(os.environ, GOOS=goos, GOARCH=goarch, CGO_ENABLED="0", GOFLAGS="-mod=mod")
    r = subprocess.run(["go", "list", "-deps", "-tags", a.tags, "-json=ImportPath,Dir,Standard,Module",
                        "./cmd/tailscaled", "./cmd/tailscale"], cwd=a.src, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("go list failed: " + r.stderr[-2000:])
    pkgs = json.loads("[" + re.sub(r"\}\s*\{", "},{", r.stdout.strip()) + "]")
    modules, main_dirs = {}, set()
    for p in pkgs:
        if p.get("Standard"):
            continue
        m = p.get("Module") or {}
        if m.get("Main"):
            main_dirs.add(p["Dir"])
            continue
        m = m.get("Replace") or m
        modules[(m["Path"], m.get("Version", ""))] = m.get("Dir")
    a.out.mkdir(parents=True, exist_ok=True)
    rows, missing = [], []
    goroot = Path(subprocess.run(["go", "env", "GOROOT"], capture_output=True, text=True, check=True).stdout.strip())
    gover = subprocess.run(["go", "env", "GOVERSION"], capture_output=True, text=True, check=True).stdout.strip()
    std = a.out / ("go-standard-library@" + gover)
    std.mkdir(exist_ok=True)
    for name in ("LICENSE", "PATENTS"):
        shutil.copyfile(goroot / name, std / name)
    rows.append(("Go standard library", gover, ["LICENSE", "PATENTS"]))
    for (path, version), d in sorted(modules.items()):
        found = licence_files(d) if d else []
        if not found:
            missing.append(path + "@" + version)
            continue
        dest = a.out / (path.replace("/", "_") + "@" + version)
        dest.mkdir(exist_ok=True)
        for f in found:
            shutil.copyfile(f, dest / f.name)
        rows.append((path, version, [f.name for f in found]))
    root = a.src.resolve()
    for d in sorted(main_dirs):
        dp = Path(d).resolve()
        for parent in [dp, *dp.parents]:
            if parent == root:
                break
            found = licence_files(parent)
            if found:
                rel = parent.relative_to(root).as_posix()
                dest = a.out / ("tailscale.com_" + rel.replace("/", "_"))
                if not dest.exists():
                    dest.mkdir()
                    for f in found:
                        shutil.copyfile(f, dest / f.name)
                    rows.append(("tailscale.com/" + rel + " (vendored in the client source)", "", [f.name for f in found]))
                break
    if missing:
        sys.exit("no licence file found for: " + ", ".join(missing))
    lines = ["# Go modules in the %s binaries" % a.target, "",
             "Generated by packaging/collect_go_licences.py from `go list -deps` with the release build tags. The",
             "client itself is tailscale.com (LICENSE-tailscale-BSD-3.txt and PATENTS-tailscale.txt next to the binaries).", "",
             "| Module | Version | Files |", "|---|---|---|"]
    lines += ["| %s | %s | %s |" % (p, v, ", ".join(f)) for p, v, f in rows]
    (a.out / "INDEX.md").write_text("\n".join(lines) + "\n")
    print("collected licences of %d modules into %s" % (len(rows), a.out))


if __name__ == "__main__":
    main()
